BIG = PER * 5     # 이름 없는 과가 60강씩 되면 목차가 아니다. 다섯 강씩 자른다.

def bucket(ko, pats):
    for name, rx in pats:
        if rx.search(ko): return name
    return None

def load_words():
    """선배 낱말 + 앱 낱말을 하나로. 겹치면 앱 것을 남기고 별표를 붙인다."""
    out = {}
    sen = json.loads((R / "data" / "_senior_split.json").read_text(encoding="utf-8"))["words"]
    for w in sen:
        if not w.get("ko"): continue
        out[key(w["vi"])] = {"vi": w["vi"], "ko": w["ko"], "pos": w.get("pos"),
                             "gi": w.get("gi", ""), "n": w.get("n", 0),
                             "field": w.get("field", "일상"), "src": "선배"}
    d = json.loads((R / "data" / "days.json").read_text(encoding="utf-8"))
    days = d if isinstance(d, list) else d["days"]
    app_n = 0
    for day in days:
        work = day.get("track") == "work"
        for w in (day.get("words") or []):
            k = key(w.get("vi", ""))
            if not k: continue
            app_n += 1
            if k in out:                                  # 겹침 — 앱 쪽 뜻과 갈래를 우선한다
                out[k]["ko"] = w.get("ko") or out[k]["ko"]
                out[k]["src"] = "둘 다"
                if work: out[k]["field"] = "직무(앱)"
            else:
                out[k] = {"vi": w["vi"], "ko": w.get("ko", ""), "pos": None, "gi": "", "n": 0,
                          "field": "직무(앱)" if work else "일상", "src": "앱"}
    print(f"선배 {len(sen)} · 앱 {app_n} · 겹침 뺀 합계 {len(out)}")
    return list(out.values())

def cut(name, arr, pats):
    """한 과의 낱말을 열 개짜리 강으로. 배운 차례가 이른 것부터."""
    arr.sort(key=lambda w: (w["pos"] if w["pos"] is not None else .5, -w["n"]))
    ch = [arr[i:i + PER] for i in range(0, len(arr), PER)]
    return {"unit": name, "words": len(arr), "chapters": len(ch),
            "sample": [w["ko"][:10] for w in arr[:6]],
            "list": [[w["vi"], w["ko"], w["n"]] for w in arr]}


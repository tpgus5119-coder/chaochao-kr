# 이름씨 + 다 (동사가 아니라 '~이다'가 줄어든 것). 규칙으로는 못 가른다.
NOTIMP = ('나라','따라','바라','거라')   # '라'로 끝나지만 시킴꼴이 아닌 말
NOUN = ['반대','장치','인사','표시','단위','전부','차례','자리','관문','부분','셈','식',
        '뜻','소리','말','때','것','지름길','시작','끝','기본','전부','절반','하나','둘',
        '이름','뜻밖','핵심','열쇠','바탕','밑천','습관','버릇','예외','규칙','원칙']
EXTRA = {}   # 규칙이 어색하게 바꾼 것만 통째로 적는다

L0, V0, T0 = 0xAC00, 588, 28
def _jamo(ch):
    if not ('가' <= ch <= '힣'): return None
    i = ord(ch) - L0
    return i // V0, (i % V0) // T0, i % T0
def _mk(a, b, c): return chr(L0 + a * V0 + b * T0 + c)

def _ending(w):
    """평서체 어미 하나를 존댓말로. 못 바꾸면 None."""
    if any(w.endswith(x) for x in NOTIMP): return None
    for a, b in RULES:
        if w.endswith(a) and len(w) > len(a) - 1: return w[:-len(a)] + b
    if w in ('있다','없다'): return w[:-1] + '습니다'
    for n in NOUN:
        if w == n + '다' or w.endswith(n + '다'): return w[:-1] + '입니다'
    if len(w) >= 2 and w.endswith('다'):
        prev = w[-2]
        j = _jamo(prev)
        if w.endswith(('았다','었다','였다','했다')): return w[:-1] + '습니다'
        if w.endswith('는다'): return w[:-2] + '습니다'
        if w.endswith('하다'): return w[:-2] + '합니다'
        if j and j[2] == 4:                     # 받침 ㄴ → 온다·간다·쓴다 → 옵니다
            return w[:-2] + _mk(j[0], j[1], 17) + '니다'
        if j and j[2] != 0:                     # 앞 글자에 받침 → 봤다·배웠다·빨갛다·않다
            return w[:-1] + '습니다'
        # 받침이 없으면 대개 '이름씨 + 다'(한자어다·예의다) — 다만 아래 낱말은 뜻씨다
        if not any(w.endswith(v) for v in
                   ('크다','나쁘다','바쁘다','아프다','고르다','다르다','빠르다','흐르다',
                    '모으다','쓰다','자다','사다','보다','오다','가다','주다','두다',
                    '지다','치다','피다','서다','타다','나다','건네다','만나다')):
            return w[:-1] + '입니다'
        return None
    return None

def polite(t):
    if not t: return t
    if t in EXTRA: return EXTRA[t]
    out = t
    # 문장 끝(마침표·물음표·느낌표·줄끝) 바로 앞의 어미만 바꾼다
    def fix(m):
        w, tail = m.group(1), m.group(2)
        r = _ending(w)
        return (r + tail) if r else m.group(0)
    # 문장 끝은 마침표만이 아니다 — 줄표(—)·물결·줄끝 앞도 문장이 끝나는 자리다
    out = re.sub(r'([가-힣]+)(\s*(?:[.!?]|—|–|~|<br>)|$)', fix, out)
    return out


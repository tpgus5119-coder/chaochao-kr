def build():
    """설계도 시간표와 문항을 합쳐 앱이 쓰는 꼴로 만든다."""
    out = []
    for si, items in enumerate(SETS):
        if len(items) != len(SPEC):
            raise SystemExit(f"{si+1}회차 문항이 {len(items)}개다 — 공식은 6개")
        qs = []
        for (kind, prep, resp, level), it in zip(SPEC, items):
            q = {"kind": kind, "prep": prep, "resp": resp, "level": level}
            q.update(it)
            qs.append(q)
        out.append({"set": si + 1, "questions": qs})
    return out



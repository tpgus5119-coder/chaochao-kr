def main():
    D = json.loads(P.read_text(encoding="utf-8"))
    n = 0
    for d in D["days"]:
        m = M.get(d["day"])
        if not m:
            continue
        if (d.get("mission") or {}).get("goal"):
            continue                      # 이미 있는 것은 손대지 않는다
        d["mission"] = {"goal": m[0], "how": m[1], "a": m[2], "b": m[3]}
        n += 1
    P.write_text(json.dumps(D, ensure_ascii=False, indent=1), encoding="utf-8")
    left = [x["day"] for x in D["days"] if not (x.get("mission") or {}).get("goal")]
    print(f"미션 {n}강 채움 · 아직 빈 강 {len(left)}개 {left}")


if __name__ == "__main__":
    main()

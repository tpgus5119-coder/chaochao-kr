def main():
    pool = json.loads((R / "data" / "_senior_pool3.json").read_text(encoding="utf-8"))["words"]
    app = {w["vi"]: w for x in json.loads((R / "data" / "days.json").read_text(encoding="utf-8"))["days"]
           for w in x.get("words") or []}
    left, out = list(pool), []
    for grp, unit, pat in TOC:
        rx = re.compile(pat)
        got = [w for w in left if rx.search(w["ko"])]
        left = [w for w in left if w not in got]
        out.append((grp, unit, got))
    print(f"선배 낱말 {len(pool)}개\n")
    g = None; tot = 0
    for grp, unit, got in out:
        if grp != g: print(f"\n■ {grp}"); g = grp
        n = len(got); ch = n // PER
        tot += n
        mark = "" if n >= PER else "   ← 열 개가 안 됨"
        print(f"   {unit:<16}{n:>5}낱말 → {ch:>2}강{mark}")
    print(f"\n담긴 낱말 {tot} · 남은 낱말 {len(left)} · 전체 강 수 약 {tot//PER}강")
